-- FORZA: MySQL 8+, InnoDB, utf8mb4. Importe em um banco vazio.
SET NAMES utf8mb4;
CREATE TABLE objetivos (id TINYINT UNSIGNED PRIMARY KEY, nome VARCHAR(80) NOT NULL) ENGINE=InnoDB;
CREATE TABLE usuarios (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, nome VARCHAR(100) NOT NULL,
 email VARCHAR(254) NOT NULL UNIQUE, senha_hash VARCHAR(255) NOT NULL,
 criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE perfis (
 usuario_id BIGINT UNSIGNED PRIMARY KEY, idade TINYINT UNSIGNED NOT NULL,
 altura DECIMAL(5,2) NOT NULL, peso DECIMAL(5,2) NOT NULL, objetivo_id TINYINT UNSIGNED NOT NULL,
 nivel ENUM('iniciante','intermediario','avancado') NOT NULL, dias_semana TINYINT UNSIGNED NOT NULL,
 minutos_treino SMALLINT UNSIGNED NOT NULL, equipamentos VARCHAR(500) NOT NULL,
 unidade_carga ENUM('kg','lb') NOT NULL DEFAULT 'kg',
 atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE,
 FOREIGN KEY(objetivo_id) REFERENCES objetivos(id),
 CHECK(idade BETWEEN 13 AND 100), CHECK(altura BETWEEN 100 AND 250), CHECK(peso BETWEEN 25 AND 400),
 CHECK(dias_semana BETWEEN 1 AND 7), CHECK(minutos_treino BETWEEN 10 AND 240)
) ENGINE=InnoDB;
CREATE TABLE exercicios (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, nome VARCHAR(100) NOT NULL UNIQUE,
 grupo_muscular VARCHAR(80) NOT NULL, equipamento VARCHAR(100) NOT NULL
) ENGINE=InnoDB;
CREATE TABLE treinos (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, usuario_id BIGINT UNSIGNED NOT NULL,
 nome VARCHAR(100) NOT NULL, dias JSON NOT NULL,
 criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE,
 INDEX idx_treinos_usuario(usuario_id)
) ENGINE=InnoDB;
CREATE TABLE treino_exercicios (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, treino_id BIGINT UNSIGNED NOT NULL,
 exercicio_id INT UNSIGNED NOT NULL, series TINYINT UNSIGNED NOT NULL,
 repeticoes SMALLINT UNSIGNED NOT NULL, carga DECIMAL(7,2) NOT NULL DEFAULT 0,
 descanso SMALLINT UNSIGNED NOT NULL DEFAULT 60, ordem SMALLINT UNSIGNED NOT NULL DEFAULT 0,
 FOREIGN KEY(treino_id) REFERENCES treinos(id) ON DELETE CASCADE,
 FOREIGN KEY(exercicio_id) REFERENCES exercicios(id),
 CHECK(series BETWEEN 1 AND 20), CHECK(repeticoes BETWEEN 1 AND 100), CHECK(carga BETWEEN 0 AND 1000),CHECK(descanso<=600)
) ENGINE=InnoDB;
CREATE TABLE sessoes_treino (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, usuario_id BIGINT UNSIGNED NOT NULL,
 treino_id BIGINT UNSIGNED NULL, nome_treino VARCHAR(100) NOT NULL,
 iniciado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, finalizado_em DATETIME NULL,
 FOREIGN KEY(usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE,
 FOREIGN KEY(treino_id) REFERENCES treinos(id) ON DELETE SET NULL,
 INDEX idx_sessoes_usuario_data(usuario_id,iniciado_em), CHECK(finalizado_em IS NULL OR finalizado_em>=iniciado_em)
) ENGINE=InnoDB;
CREATE TABLE series_realizadas (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, sessao_id BIGINT UNSIGNED NOT NULL,
 exercicio_id INT UNSIGNED NOT NULL, nome_exercicio VARCHAR(100) NOT NULL,
 numero TINYINT UNSIGNED NOT NULL, repeticoes SMALLINT UNSIGNED NOT NULL,
 carga DECIMAL(7,2) NOT NULL, descanso SMALLINT UNSIGNED NOT NULL DEFAULT 60,
 concluida BOOLEAN NOT NULL DEFAULT FALSE,
 FOREIGN KEY(sessao_id) REFERENCES sessoes_treino(id) ON DELETE CASCADE,
 FOREIGN KEY(exercicio_id) REFERENCES exercicios(id),
 CHECK(numero BETWEEN 1 AND 20), CHECK(repeticoes BETWEEN 1 AND 100), CHECK(carga BETWEEN 0 AND 1000)
) ENGINE=InnoDB;
CREATE TABLE alimentos (
 id INT UNSIGNED PRIMARY KEY, nome VARCHAR(150) NOT NULL,
 calorias DECIMAL(7,2) NOT NULL, proteinas DECIMAL(7,2) NOT NULL,
 carboidratos DECIMAL(7,2) NOT NULL, gorduras DECIMAL(7,2) NOT NULL,
 fonte VARCHAR(500) NOT NULL, INDEX idx_alimentos_nome(nome),
 CHECK(calorias>=0),CHECK(proteinas>=0),CHECK(carboidratos>=0),CHECK(gorduras>=0)
) ENGINE=InnoDB;
CREATE TABLE refeicoes (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, usuario_id BIGINT UNSIGNED NOT NULL,
 nome VARCHAR(100) NOT NULL, data DATE NOT NULL,
 criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE,
 INDEX idx_refeicoes_usuario_data(usuario_id,data)
) ENGINE=InnoDB;
CREATE TABLE refeicao_alimentos (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, refeicao_id BIGINT UNSIGNED NOT NULL,
 alimento_id INT UNSIGNED NOT NULL, gramas DECIMAL(8,2) NOT NULL,
 FOREIGN KEY(refeicao_id) REFERENCES refeicoes(id) ON DELETE CASCADE,
 FOREIGN KEY(alimento_id) REFERENCES alimentos(id), CHECK(gramas BETWEEN 1 AND 5000)
) ENGINE=InnoDB;
CREATE TABLE dicas (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, objetivo_id TINYINT UNSIGNED NOT NULL,
 titulo VARCHAR(150) NOT NULL, conteudo TEXT NOT NULL, categoria VARCHAR(80) NOT NULL,
 fonte VARCHAR(500) NOT NULL, FOREIGN KEY(objetivo_id) REFERENCES objetivos(id)
) ENGINE=InnoDB;
CREATE TABLE registros_peso (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, usuario_id BIGINT UNSIGNED NOT NULL,
 data DATE NOT NULL, peso DECIMAL(5,2) NOT NULL,
 criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE,
 UNIQUE KEY uk_peso_usuario_data(usuario_id,data), CHECK(peso BETWEEN 25 AND 400)
) ENGINE=InnoDB;
CREATE TABLE medidas_corporais (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, usuario_id BIGINT UNSIGNED NOT NULL,
 data DATE NOT NULL, cintura DECIMAL(5,2) NOT NULL, quadril DECIMAL(5,2) NOT NULL, braco DECIMAL(5,2) NOT NULL,
 criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE,
 UNIQUE KEY uk_medidas_usuario_data(usuario_id,data),
 CHECK(cintura BETWEEN 20 AND 250),CHECK(quadril BETWEEN 20 AND 250),CHECK(braco BETWEEN 10 AND 100)
) ENGINE=InnoDB;
CREATE TABLE tentativas_login (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, ip_hash CHAR(64) NOT NULL,
 email_hash CHAR(64) NOT NULL, criado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_tentativas_ip(ip_hash,criado_em), INDEX idx_tentativas_email(email_hash,criado_em),INDEX idx_tentativas_data(criado_em)
) ENGINE=InnoDB;
